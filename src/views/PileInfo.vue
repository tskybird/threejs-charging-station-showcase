<!-- 一眼看懂充电桩状态：绿、蓝、红的秘密
给电动车充电时，面对充电桩上闪烁的灯光和屏幕信息，你是否感到困惑？其实，绝大部分充电桩都通过指示灯颜色、屏幕文字和动态效果来清晰展示状态。掌握这套“通用语言”，你就能一眼识别，高效充电。
1. 待机状态（准备就绪） 这是桩体空闲、等待服务的状态。
指示灯：通常为常亮绿色或白色。绿色最为常见，代表设备正常、电源接通且未占用。
屏幕显示：屏幕上一般会显示欢迎语、二维码、操作指引或“请连接车辆”、“待机”等文字。枪头通常安放在枪座上。
关键特征：灯光稳定，屏幕静止，整体状态“安静”。看到这个状态，你就可以放心上前扫码或刷卡启动。
2. 充电状态（工作中） 车辆连接并启动充电后进入此状态。
指示灯：变为蓝色或绿色闪烁/呼吸。呼吸或规律闪烁的灯光是“正在充电”最直观的信号。
屏幕显示：屏幕信息变得动态丰富，核心数据包括：实时充电功率（kW）、已充电量（kWh）、充电时长、费用信息等。通常会有一个明显的进度条或电池图标填充动画。
关键特征：灯光动态闪烁，屏幕数据实时更新。听到桩体内有接触器吸合声或风扇运转声，也属正常。 -->


